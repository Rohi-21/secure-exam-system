/**
 * Authoritative Examination & Cryptographic API Contracts
 *
 * Single source of truth shared across client and server.
 * Ensures consistent field names, encodings, and cryptographic parameters.
 */

// ── 1. Ephemeral ECDH Handshake Contract ───────────────────────────────────

export interface ECDHHandshakeRequest {
  /** Client's ephemeral NIST P-256 public key (raw 65-byte uncompressed, base64) */
  clientEphemeralPubKeyB64: string;
}

export interface ECDHHandshakeResponse {
  /** Server's ephemeral NIST P-256 public key (raw 65-byte uncompressed, base64) */
  serverEphemeralPubKeyB64: string;
  /** Server's Ed25519 signature over canonical handshake transcript */
  signature: string;
  /** Unique exam session ID generated by the server */
  sessionId: string;
  /** Cryptographic anti-replay nonce (64-char hex) */
  nonce: string;
  /** Server timestamp (Unix ms) */
  timestamp: number;
  /** Bound Exam ID */
  examId: string;
  /** Bound Student User ID */
  studentId: string;
  /** Server's long-term Ed25519 public key (PEM or SPKI base64) for verification */
  serverEd25519PubKey: string;
}

export interface HandshakeTranscriptPayload {
  serverEphemeralPubKeyB64: string;
  clientEphemeralPubKeyB64: string;
  examId: string;
  sessionId: string;
  nonce: string;
  timestamp: number;
  studentId: string;
}

// ── 2. Questions Delivery Contract ──────────────────────────────────────────

export interface DeliveredQuestionItem {
  questionNo: number;
  /** Ciphertext encrypted under student's ephemeral session K_enc (base64) */
  ciphertext: string;
  /** AES-256-GCM auth tag (base64) */
  authTag: string;
  /** AES-256-GCM 96-bit IV (base64) */
  iv: string;
  /** JSON stringified AAD bound to the question */
  aad: string;
}

export interface QuestionsDeliveryResponse {
  questions: DeliveredQuestionItem[];
  total: number;
  durationMins: number;
  startTime: string; // ISO string
  endTime: string;   // ISO string
  serverTime: string; // ISO string
}

export interface QuestionPlaintext {
  questionNo: number;
  text: string;
  optionA: string;
  optionB: string;
  optionC: string;
  optionD: string;
}

// ── 3. Submission Contract ──────────────────────────────────────────────────

export interface CanonicalAnswerMap {
  [questionNo: string]: string; // e.g. { "1": "B", "2": "C" }
}

export interface StudentSubmissionPayload {
  examId: string;
  studentId: string;
  sessionId: string;
  submissionNonce: string;
  answers: CanonicalAnswerMap;
  submittedAt: string; // ISO string
}

export interface SubmissionRequest {
  /** Exam session ID negotiated during ECDH */
  sessionId: string;
  /** Single-use anti-replay submission nonce (UUID or 32B hex) */
  submissionNonce: string;
  /** SHA-256 hex digest of the canonical submission payload */
  contentHash: string;
  /** Student's ECDSA-P256 signature (IEEE P1363 or DER, base64) over the contentHash */
  ecdsaSignature: string;
  /**
   * Application-layer encrypted submission payload:
   * AES-256-GCM under session K_enc with fresh 12-byte IV and AAD
   */
  encryptedPayload: {
    ciphertext: string;
    authTag: string;
    iv: string;
    aad: string;
  };
}

export interface SubmissionResponse {
  message: string;
  submissionId: string;
  contentHash: string;
  submittedAt: string;
}

